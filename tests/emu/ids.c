/* The firmware's internal ids that tests/emu (emu_test) drives the device with, printed as Rust from the same
 * sources: the parameters the heavy patch sets (core.h), the punch-in effects and the two punch pages' key maps
 * (perform.c PF_DEF / PF2_DEF, white keys F3 .. G5). Protocol constants (editor commands, menu ids, engine
 * numbers) are append-only by their own rules and stay in emu_test.
 *   build/host/emu_ids > build/emu/ids.rs     (tests/run_tests.sh, FM1_EMU=1; emu_test include!s it) */
#define main hostsim_main
#include "../hostsim.c"
#undef main

static void u8c(const char *name, int v) { printf("pub const %s: u8 = %d;\n", name, v); }
static void u32c(const char *name, unsigned v) { printf("pub const %s: u32 = %u;\n", name, v); }
static void keys(const char *name, const uint8_t *map)
{
    unsigned i;
    printf("pub const %s: [u32; %u] = [", name, (unsigned)PF_KEYS);
    for (i = 0; i < PF_KEYS; i++)
        printf("%s%u", i ? ", " : "", (unsigned)map[i]);
    printf("];\n");
}

int main(void)
{
    printf("// generated by tests/emu/ids.c from the firmware sources: do not edit\n");
    u8c("P_SUS", P_SUS);
    u8c("P_AMODE", P_AMODE);
    u8c("P_DLY", P_DLY);
    u8c("P_REV", P_REV);
    u8c("P_VOICE", P_VOICE);
    printf("pub const INSERT_MIX: [u8; 6] = [%d, %d, %d, %d, %d, %d];\n", P_IDMIX, P_IFMIX, P_ICMIX, P_IPMIX, P_ILMIX,
           P_IHMIX);
    u8c("G_BPM", G_BPM);
    u8c("G_ROUTE", G_ROUTE);                        /* MENU > MIDI > MIDI IN: 0 = CH1-4 play parts 1-4 (seq.c midi_base) */
    printf("pub const V_POLY: i32 = %d;\n", V_POLY);
    u32c("PF_R8", PF_R8);
    u32c("PF_R12", PF_R12);
    u32c("PF_R16", PF_R16);
    u32c("PF_R32", PF_R32);
    u32c("PF_REV", PF_REV);
    u32c("PF_LPF", PF_LPF);
    u32c("PF_HPF", PF_HPF);
    u32c("PF_TAPE", PF_TAPE);
    u32c("PF_FRZ", PF_FRZ);
    u32c("PF_OUP", PF_OUP);
    u32c("PF_ODN", PF_ODN);
    u32c("PF_FLG", PF_FLG);
    u32c("PF_PHS", PF_PHS);
    u32c("PF_RTHR", PF_RTHR);
    u32c("PF_ETHR", PF_ETHR);
    u32c("PF_GLT", PF_GLT);
    u32c("PF_OCTD", PF_OCTD);                       /* PF_OCTD .. PF_X2: the MIDI effects (pfx.c) */
    u32c("PF_X2", PF_X2);
    u32c("PF_N", PF_N);
    keys("PF_PAGE1", PF_DEF);
    keys("PF_PAGE2", PF2_DEF);
    return 0;
}
